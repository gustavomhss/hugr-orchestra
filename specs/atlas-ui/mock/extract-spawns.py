# Extracts the live continuity runs (specs/backend-specialist/evidence/continuity-live-2026-10-10) into the
# preview: one task unit per run, with its invocations, the seat session transcript, checkpoints and admissions.
import json, os, sys, glob
SRC = sys.argv[1]
OUT = sys.argv[2]
cut = lambda s, n: (s if len(s) <= n else s[:n] + "…") if isinstance(s, str) else s
KIND = {"01-dispatch": "dispatch", "02-resume": "resume", "03-interim": "interim", "04-compact": "compact", "05-continue": "continue"}
tasks = []
for run in sorted(glob.glob(os.path.join(SRC, "attempt-*"))):
    read = lambda f: open(os.path.join(run, f)).read().strip() if os.path.exists(os.path.join(run, f)) else ""
    cmds = [json.loads(l) for l in read("commands.jsonl").splitlines() if l.strip()]
    starts = {c["label"]: c for c in cmds if "start" in c}
    ends = {c["label"]: c["end"] for c in cmds if "end" in c}
    steps = [{"label": label, "kind": KIND.get(label, label), "start": c["start"], "end": ends.get(label), "model": c.get("model"),
              "packet": cut(read(f"{label}.txt"), 1600), "result": cut(read(f"{label}.summary.txt"), 1600)} for label, c in starts.items()]
    path = os.path.join(run, "child-session.messages.json")
    if os.path.exists(path):
        messages, title = json.load(open(path)), None
    else:
        export = json.load(open(os.path.join(run, "child-session.export.json")))
        messages, title = export["messages"], export["info"].get("title")
    transcript, checkpoints, admissions = [], [], []
    for msg in messages:
        info = msg["info"]
        parts = []
        for p in msg["parts"]:
            t = p["type"]
            if t == "text":
                meta = p.get("metadata") or {}
                adm = meta.get("atlasResume")
                if adm:
                    admissions.append({"ref": (adm.get("verdict") or {}).get("ref"), "ok": (adm.get("verdict") or {}).get("ok"), "residency": adm.get("residency"), "unit": adm.get("key", {}).get("id"), "at": info["time"]["created"]})
                parts.append({"type": "admission" if adm else "text", "text": cut(p["text"], 1400), "synthetic": bool(p.get("synthetic"))})
            elif t == "reasoning":
                parts.append({"type": "reasoning", "text": cut(p["text"], 700)})
            elif t == "tool":
                st = p["state"]
                md = st.get("metadata") or {}
                rec = md.get("atlasMemory")
                item = {"type": "tool", "tool": p.get("tool"), "status": st.get("status"), "input": cut(json.dumps(st.get("input"), ensure_ascii=False), 300), "output": cut(str(st.get("output") or st.get("error") or ""), 400)}
                if md.get("toolSafety"): item["held"] = cut(json.dumps(md["toolSafety"], ensure_ascii=False), 300)
                if rec:
                    item["receipt"] = {"op": rec.get("op"), "outcome": rec.get("outcome"), "refusal": (rec.get("refusal") or {}).get("refusal"), "reason": cut((rec.get("refusal") or {}).get("reason") or "", 220), "ref": (rec.get("ref") or {}).get("eventId")}
                    if rec.get("op") == "emit":
                        entry = (st.get("input") or {}).get("entry") or {}
                        checkpoints.append({"outcome": rec.get("outcome"), "refusal": item["receipt"]["refusal"], "reason": item["receipt"]["reason"], "ref": item["receipt"]["ref"], "entry": entry, "at": info["time"]["created"], "callID": rec.get("binding", {}).get("callID")})
                parts.append(item)
        if parts:
            tokens = info.get("tokens") or {}
            transcript.append({"role": info["role"], "model": info.get("modelID"), "at": info["time"]["created"], "tokens": {"in": tokens.get("input", 0), "out": tokens.get("output", 0), "cache": (tokens.get("cache") or {}).get("read", 0)}, "parts": parts})
    unit = next((c["entry"].get("taskId") for c in checkpoints if c["entry"].get("taskId")), None)
    tasks.append({"run": os.path.basename(run)[-1], "unit": unit, "member": "backend", "taskRef": read("task.id"), "seatSession": read("child.sid"), "maestroSession": read("maestro.sid"),
                  "title": title, "steps": steps, "transcript": transcript, "checkpoints": checkpoints, "admissions": admissions, "diff": cut(read("repo.diff"), 1500)})
with open(OUT, "w") as f:
    f.write("// Generated by extract-spawns.py from specs/backend-specialist/evidence/continuity-live-2026-10-10 (live runs, 2026-10-11).\n")
    f.write("window.Atlas = window.Atlas || {}\nwindow.Atlas.spawns = ")
    json.dump(tasks, f, ensure_ascii=False, separators=(",", ":"))
    f.write("\n")
print([(t["run"], t["unit"], len(t["steps"]), len(t["transcript"]), len(t["checkpoints"]), len(t["admissions"])) for t in tasks], os.path.getsize(OUT))
