#!/usr/bin/env bun
// Dev tool: prints the rule catalog as Markdown, generated from the rule files so it cannot drift from them. Samples stay
// in the rule files: printed here, credential and conflict-marker samples would trip the guards on the catalog itself.
//
// Usage: bun run script/guards/catalog.ts > docs/guardrail/catalog.md

import { readdirSync, readFileSync } from "node:fs"
import path from "node:path"
import { parseRule, type Rule } from "./rule"

const dir = path.join(import.meta.dir, "rules")
const rules = readdirSync(dir)
  .sort()
  .map((file) => parseRule(file, readFileSync(path.join(dir, file), "utf8")))
  .filter((rule): rule is Rule => typeof rule !== "string")

const sections = [
  { title: "Gate rules on added lines", pick: (r: Rule) => r.severity === "gate" && r.on === "added-lines" },
  { title: "Gate rules on changed paths", pick: (r: Rule) => r.severity === "gate" && r.on === "changed-paths" },
  { title: "Gate rules on line balance", pick: (r: Rule) => r.severity === "gate" && r.on === "line-balance" },
  { title: "Warn rules on added lines", pick: (r: Rule) => r.severity === "warn" && r.on === "added-lines" },
  { title: "Warn rules on changed paths", pick: (r: Rule) => r.severity === "warn" && r.on === "changed-paths" },
  { title: "Warn rules on line balance", pick: (r: Rule) => r.severity === "warn" && r.on === "line-balance" },
]

const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ")

const body = sections.flatMap((section) => {
  const picked = rules.filter(section.pick)
  if (picked.length === 0) return []
  return [
    `## ${section.title} (${picked.length})`,
    "",
    "| Rule | Message |",
    "|---|---|",
    ...picked.map((r) => `| \`${r.id}\` | ${cell(r.message)} |`),
    "",
  ]
})

console.log(
  [
    "# Guardrail rule catalog",
    "",
    "Generated by `bun run script/guards/catalog.ts > docs/guardrail/catalog.md`. Do not edit by hand: change the rule file in `script/guards/rules/` and regenerate.",
    "",
    `${rules.length} rules: ${rules.filter((r) => r.severity === "gate").length} gate (fail the pull request), ${rules.filter((r) => r.severity === "warn").length} warn (annotation only).`,
    "",
    ...body,
  ].join("\n"),
)
