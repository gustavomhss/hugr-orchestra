// Shared reader for script/module-architecture.json (layers, ownership, legacy labels) and the helpers that
// script/check-module-boundaries.ts and its generators share. Workspace specifiers resolve only through the working
// tree's package.json `exports`, never through node_modules: card worktrees symlink another checkout's node_modules.
import { readFileSync } from "node:fs"
import path from "node:path"
import ts from "typescript"

export type Domain = { kind: string; patterns: string[]; entry?: string; target?: string }
export type Module = { path: string; kind: "cohesive" | "collection"; entries?: string[]; status?: string; successor?: string }
export type Package = {
  layer: string; status: "canonical" | "legacy" | "unused"; owner: string; summary: string
  exportsPolicy: "full" | "demanded" | "none"; successor?: string; live?: string; entries?: string[]
  assetWildcards?: string[]; browserSafe?: string[]; platformLibrary?: boolean; aliases?: Record<string, string>
  modules?: Module[]; domains?: Record<string, Domain>
}
export type Legacy = {
  path?: string; specifier?: string; label?: string; status: "legacy" | "vendored" | "unused" | "duplicate"
  successor?: string; reason: string; decision: string; compat?: Record<string, string>
}
export type Architecture = {
  format: 1; layers: Record<string, string[]>; packages: Record<string, Package>; legacy: Legacy[]
  productEdges: [string, string][]; relayContainment: { package: string; specifier: string; domains: string[] }
  logicalModules: { id: string; paths: string[]; readme: string; target: string }[]
  assetModules: { id: string; path: string; target: string }[]; scaffoldReadmes: string[]
}
type Dependencies = Record<string, string>
export type Manifest = {
  name?: string; main?: string; exports?: unknown; dependencies?: Dependencies; devDependencies?: Dependencies
  peerDependencies?: Dependencies; optionalDependencies?: Dependencies
}
export type Member = { alias: string; name: string; path: string; spec: Package; manifest: Manifest; manifestText: string }
export type Workspace = ReturnType<typeof loadWorkspace>

export const README_START =
  "<!-- module-contract:start (generated by script/module-readme.ts from script/module-architecture.json; do not edit) -->"
export const README_END = "<!-- module-contract:end -->"
export const SOURCE = /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs)$/
// script/, campaign/ and the like are support code inside a package, but a workspace may itself be named
// after one of them (packages/script), so those names never match as the workspace directory.
const TEST =
  /(^|\/)(test|tests|e2e|test-browser|fixture|fixtures|__tests__|\.storybook)\/|(^|(?<!^(?:packages|apps|modules|tooling))\/)(script|scripts|campaign|example|examples|benchmark)\/|\.(test|spec|stories|fixture|suite|test-helper)\.[cm]?[jt]sx?$/

export function isTestFile(file: string) {
  return TEST.test(file)
}

export function loadWorkspace(root: string) {
  const read = (file: string) => readFileSync(path.join(root, file), "utf8")
  const registry = (JSON.parse(read("script/module-registry.json")) as { modules: { alias: string; name: string; path: string }[] }).modules
  const architecture = decodeArchitecture(JSON.parse(read("script/module-architecture.json")))
  const members: Member[] = registry.flatMap((entry) => {
    const spec = architecture.packages[entry.alias]
    if (spec === undefined) return []
    const manifestText = read(`${entry.path}/package.json`)
    return [{ ...entry, spec, manifest: JSON.parse(manifestText) as Manifest, manifestText }]
  })
  const byLength = [...members].sort((a, b) => b.path.length - a.path.length)
  return {
    root,
    registry,
    architecture,
    members,
    files: listFiles(root),
    memberOf: (file: string) => byLength.find((member) => file.startsWith(`${member.path}/`)),
    member: (alias: string) => members.find((member) => member.alias === alias),
  }
}

export function listFiles(root: string) {
  const git = (args: string[]) => {
    const result = Bun.spawnSync(["git", ...args], { cwd: root })
    if (result.exitCode !== 0) throw new Error(`GIT_LS_FILES_FAILED: ${result.stderr.toString().trim()}`)
    return result.stdout.toString().split("\0").filter(Boolean)
  }
  const deleted = new Set(git(["ls-files", "-d", "-z"]))
  return git(["ls-files", "-co", "--exclude-standard", "-z"]).filter((file) => !deleted.has(file))
}

/** Node `exports` matching: an exact key first, then the pattern with the longest prefix before `*`, then the longest key. */
export function resolveExport(exportsMap: unknown, subpath: string) {
  const map = exportsObject(exportsMap)
  if (map[subpath] !== undefined) {
    const target = pickTarget(map[subpath])
    return target === undefined ? undefined : { key: subpath, target }
  }
  const key = Object.keys(map)
    .filter((candidate) => {
      const star = candidate.indexOf("*")
      if (star < 0 || candidate.indexOf("*", star + 1) >= 0) return false
      return subpath.startsWith(candidate.slice(0, star)) && subpath.endsWith(candidate.slice(star + 1)) && subpath.length >= candidate.length
    })
    .sort((a, b) => b.indexOf("*") - a.indexOf("*") || b.length - a.length)[0]
  if (key === undefined) return undefined
  const star = key.indexOf("*")
  const target = pickTarget(map[key])
  return target === undefined ? undefined : { key, target: target.replaceAll("*", subpath.slice(star, subpath.length - (key.length - star - 1))) }
}

export function exportsObject(exportsMap: unknown): Record<string, unknown> {
  if (typeof exportsMap === "string") return { ".": exportsMap }
  if (!exportsMap || typeof exportsMap !== "object" || Array.isArray(exportsMap)) return {}
  const entries = Object.entries(exportsMap)
  return entries.every(([key]) => key.startsWith(".")) ? Object.fromEntries(entries) : { ".": exportsMap }
}

function pickTarget(value: unknown): string | undefined {
  if (typeof value === "string") return value
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined
  return Object.entries(value)
    .filter(([condition]) => condition !== "types")
    .map(([, nested]) => pickTarget(nested))
    .find((target) => target !== undefined)
}

/** Domain ids that own a package-relative file: exact file beats `dir/name*` beats the longest `dir/`. */
export function ownerOf(file: string, domains: Record<string, Domain>) {
  const hits = Object.entries(domains).flatMap(([id, domain]) =>
    domain.patterns.map((pattern) => ({ id, rank: patternRank(pattern, file) })).filter((hit) => hit.rank > 0),
  )
  const top = Math.max(0, ...hits.map((hit) => hit.rank))
  return [...new Set(hits.filter((hit) => hit.rank === top).map((hit) => hit.id))]
}

export function patternRank(pattern: string, file: string) {
  if (pattern.endsWith("/")) return file.startsWith(pattern) ? pattern.length : 0
  if (!pattern.includes("*")) return pattern === file ? 20_000 : 0
  const head = pattern.slice(0, pattern.indexOf("*"))
  const tail = pattern.slice(pattern.indexOf("*") + 1)
  return file.startsWith(head) && file.endsWith(tail) && !file.slice(head.length, file.length - tail.length).includes("/") ? 10_000 : 0
}

export type Specifier = { specifier: string; kind: string; typeOnly: boolean; start: number; end: number; unsupported: boolean }

/** Every module specifier in an import position. Strings elsewhere, such as Effect service tags, are not imports. */
export function specifiersOf(file: string, text: string) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false, scriptKind(file))
  const found: Specifier[] = []
  const add = (node: ts.Node | undefined, kind: string, typeOnly: boolean, unsupported = false) => {
    if (node && ts.isStringLiteralLike(node))
      found.push({ specifier: node.text, kind, typeOnly, start: node.getStart(source) + 1, end: node.getEnd() - 1, unsupported })
  }
  const visit = (node: ts.Node): void => {
    if (ts.isImportDeclaration(node)) {
      const clause = node.importClause
      const named = clause?.namedBindings && ts.isNamedImports(clause.namedBindings) ? clause.namedBindings.elements : undefined
      const typeOnly = !!clause && (clause.isTypeOnly || (!clause.name && !!named && named.length > 0 && named.every((item) => item.isTypeOnly)))
      const unsupported = !!clause && (!!clause.name || (!!clause.namedBindings && ts.isNamespaceImport(clause.namedBindings)))
      add(node.moduleSpecifier, "import", typeOnly, unsupported)
    }
    if (ts.isExportDeclaration(node)) {
      const named = node.exportClause && ts.isNamedExports(node.exportClause) ? node.exportClause.elements : undefined
      add(node.moduleSpecifier, "export", node.isTypeOnly || (!!named && named.length > 0 && named.every((item) => item.isTypeOnly)))
    }
    if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference))
      add(node.moduleReference.expression, "import-equals", node.isTypeOnly)
    if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)) add(node.argument.literal, "import-type", true)
    if (ts.isCallExpression(node)) {
      const callee = node.expression
      if (callee.kind === ts.SyntaxKind.ImportKeyword) add(node.arguments[0], "dynamic", false)
      if (ts.isIdentifier(callee) && callee.text === "require") add(node.arguments[0], "require", false)
      if (ts.isPropertyAccessExpression(callee) && callee.name.text === "glob" && ts.isMetaProperty(callee.expression)) {
        const first = node.arguments[0]
        if (first && ts.isArrayLiteralExpression(first)) first.elements.forEach((element) => add(element, "glob", false))
        add(first, "glob", false)
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return found
}

function scriptKind(file: string) {
  if (file.endsWith(".tsx")) return ts.ScriptKind.TSX
  if (file.endsWith(".jsx")) return ts.ScriptKind.JSX
  return /\.[cm]?js$/.test(file) ? ts.ScriptKind.JS : ts.ScriptKind.TS
}

export function renderReadmeBlock(workspace: Workspace, alias: string) {
  const member = workspace.member(alias)
  if (!member) throw new Error(`MODULE_ALIAS_UNKNOWN:${alias}`)
  const spec = member.spec
  const code = (value: string) => `\`${value}\``
  const ref = (value: string) => (value.includes(" ") ? value : code(value))
  const layers = workspace.architecture.layers[spec.layer] ?? []
  const legacy = workspace.architecture.legacy
    .filter((item) => item.path !== undefined && (item.path === member.path || item.path.startsWith(`${member.path}/`)))
    .map((item) => `${item.label ?? code(item.path ?? "")} (${item.status}${item.successor ? `, successor ${ref(item.successor)}` : ""})`)
  const entry = member.manifest.exports
    ? "explicit `exports` in package.json"
    : member.manifest.main
      ? `${code("main")} field (${code(member.manifest.main)})`
      : "application entrypoint, no library exports"
  const domains = Object.entries(spec.domains ?? {}).map(
    ([id, domain]) => `- ${code(id)} — ${domain.kind} — ${domain.patterns.map(code).join(", ")} — ${domain.target ?? member.path}`,
  )
  return [
    README_START,
    "## Module contract",
    `- Package: ${code(member.name)} at ${code(member.path)} (alias ${code(alias)})`,
    `- Summary: ${spec.summary}`,
    `- Layer: ${code(spec.layer)}; may depend on: ${layers.length ? layers.map(code).join(", ") : "nothing (base layer)"}`,
    `- Status: ${code(spec.status)}${spec.successor ? `; successor: ${ref(spec.successor)}` : ""}${spec.live ? `; live: ${spec.live}` : ""}`,
    `- Owner: ${spec.owner}`,
    `- Public entry: ${entry}`,
    `- Legacy and compatibility: ${legacy.length ? legacy.join("; ") : "none"}`,
    "- Enforced by `bun run check:boundaries`; exceptions in `script/boundary-ledger.json`.",
    ...(domains.length ? ["", "### Domains", ...domains] : []),
    README_END,
  ].join("\n")
}

/** Structural decode with named failures; registry content (paths, patterns, layers) is checked by rule R0. */
export function decodeArchitecture(value: unknown): Architecture {
  const fail = (where: string): never => {
    throw new Error(`ARCHITECTURE_INVALID:${where}`)
  }
  const object = (input: unknown, where: string) =>
    !input || typeof input !== "object" || Array.isArray(input) ? fail(where) : (input as Record<string, unknown>)
  const strings = (input: unknown, where: string) =>
    Array.isArray(input) && input.every((item) => typeof item === "string" && item.length > 0) ? (input as string[]) : fail(where)
  const oneOf = (input: unknown, allowed: string[], where: string) => (allowed.includes(String(input)) ? input : fail(where))
  const list = (input: unknown, where: string) => (Array.isArray(input) ? (input as unknown[]) : fail(where))
  const top = object(value, "root")
  oneOf(top.format, ["1"], "format")
  Object.entries(object(top.layers, "layers")).forEach(([name, allowed]) => strings([name, ...list(allowed, `layers.${name}`)], `layers.${name}`))
  Object.entries(object(top.packages, "packages")).forEach(([alias, input]) => {
    const spec = object(input, `packages.${alias}`)
    strings(["layer", "owner", "summary"].map((field) => spec[field]), `packages.${alias}`)
    oneOf(spec.status, ["canonical", "legacy", "unused"], `packages.${alias}.status`)
    oneOf(spec.exportsPolicy, ["full", "demanded", "none"], `packages.${alias}.exportsPolicy`)
    ;["entries", "assetWildcards", "browserSafe"].forEach((field) => spec[field] === undefined || strings(spec[field], `packages.${alias}.${field}`))
    Object.entries(spec.domains === undefined ? {} : object(spec.domains, `packages.${alias}.domains`)).forEach(([id, domain]) =>
      strings(object(domain, `packages.${alias}.domains.${id}`).patterns, `packages.${alias}.domains.${id}.patterns`),
    )
    list(spec.modules ?? [], `packages.${alias}.modules`).forEach((module, index) => {
      const item = object(module, `packages.${alias}.modules.${index}`)
      strings([item.path], `packages.${alias}.modules.${index}.path`)
      oneOf(item.kind, ["cohesive", "collection"], `packages.${alias}.modules.${index}.kind`)
    })
  })
  list(top.legacy, "legacy").forEach((input, index) => {
    const item = object(input, `legacy.${index}`)
    strings([item.path ?? item.specifier, item.reason, item.decision], `legacy.${index}`)
    oneOf(item.status, ["legacy", "vendored", "unused", "duplicate"], `legacy.${index}.status`)
  })
  strings(object(top.relayContainment, "relayContainment").domains, "relayContainment.domains")
  list(top.productEdges, "productEdges").forEach((edge) => strings(edge, "productEdges").length === 2 || fail("productEdges"))
  strings(top.scaffoldReadmes, "scaffoldReadmes")
  list(top.logicalModules, "logicalModules").forEach((item, index) => strings(object(item, `logicalModules.${index}`).paths, `logicalModules.${index}`))
  list(top.assetModules, "assetModules").forEach((item, index) => strings([object(item, `assetModules.${index}`).path], `assetModules.${index}`))
  return value as Architecture
}
