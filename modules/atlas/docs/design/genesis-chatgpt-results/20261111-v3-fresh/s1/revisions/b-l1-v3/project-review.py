"""Project the preserved native readings onto the original B1/B2/B3 review bar."""
from pathlib import Path
import hashlib,json,runpy
HERE=Path(__file__).resolve().parent;ROOT=HERE.parent.parent
sha=lambda b:hashlib.sha256(b).hexdigest()
def save(name,value):
 p=HERE/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
def ident(p):
 b=p.read_bytes();return {'path':str(p.relative_to(ROOT)),'sha256':sha(b),'byte_length':len(b)}
def spans(nums):
 out=[]
 for i in sorted(set(nums)):
  if out and out[-1][1]+1==i:out[-1][1]=i
  else:out.append([i,i])
 return out
def metadata(raw,lines,a,z):
 b=b''.join(lines[a-1:z]);start=sum(map(len,lines[:a-1]));return {'start_line':a,'end_line':z,'byte_start':start,'byte_end_exclusive':start+len(b),'byte_length':len(b),'sha256':sha(b)}

plan=runpy.run_path(str(HERE/'compact-plan.py'))
# These files are regenerated by build-evidence.py; the full projections are preserved before a compact overwrite.
for rel in ['semantic-disposition.json','source-excerpts.json','review-supplement.md']:
 p=HERE/rel;out=HERE/'support'/('full-'+rel);out.parent.mkdir(parents=True,exist_ok=True);out.write_bytes(p.read_bytes())
full=json.loads((HERE/'support/full-semantic-disposition.json').read_text())
fs=json.loads((HERE/'support/full-source-excerpts.json').read_text())
members=full['members'];byfile={x['path']:x for x in members};byid={x['id']:x for x in fs['sources']}
assignment={};domains=[]
for did,title,selectors,claim,gap in plan['REVIEW_DOMAINS']:
 paths=[]
 for selector in selectors:
  if selector.startswith('server:'):
   names=set(selector.split(':',1)[1].split(','))
   paths += [x['path'] for x in members if x['path'].startswith('packages/server/src/handlers/') and Path(x['path']).name in names]
  else: paths += [x['path'] for x in members if x['domain_id']==selector]
 assert paths and len(paths)==len(set(paths)),(did,paths)
 for path in paths:
  assert path not in assignment,(path,did,assignment.get(path));assignment[path]=did
 domains.append({'id':did,'title':title,'member_paths':sorted(paths),'member_count':len(paths),
  'current_l1_need':'Mandatory now: identify this domain’s role, public contract and local owner/delegation boundary from literal source, without projecting an unseen runtime guarantee.',
  'bounded_claim':claim,'conditional_gap':gap,'blocked_dependents':'Any current or later claim relying on the named broader behavior requires that additional implementation/runtime evidence. Current local L1 reading was performed now.',
  'local_source_need_status':'addressed_for_review','semantic_acceptance':'unjudged','depth':'full_source_read_for_bounded_L1_purpose_contract_ownership',
  'why_depth_adequate':'Every listed handwritten member was read in full; the projection supplies decisive declaration/delegation/ownership branches and identifies external enforcement limits. It does not infer semantics from inventory or require an unrequested leaf-by-leaf operational audit.'})
assert set(assignment)==set(byfile) and len(assignment)==190

# Compact exact-line selection. All removed material remains in the preserved full support projection.
chosen={}
for eid,s in byid.items():
 path=s['source_ref']['path'];ranges=s['requested_ranges']
 if eid.startswith('V'): pass
 elif eid.startswith('Q'):
  short=path.removeprefix('packages/schema/src/')
  ranges=plan['SCHEMA_RANGES'].get(short,ranges)
 elif eid.startswith('P'):
  indexes=[0]+plan['PROTOCOL_EXTRA'].get(eid,[])
  ranges=[ranges[i] for i in indexes]
 elif eid.startswith('G57-E'):
  if int(eid.removeprefix('G57-E')) not in plan['SERVER_IDS']:continue
  ranges=plan['SERVER_RANGES'].get(eid,ranges)
 else:raise AssertionError(eid)
 allowed=set(n for rg in s['ranges'] for n in range(rg['start_line'],rg['end_line']+1))
 wanted=set(n for a,z in ranges for n in range(a,z+1))
 # Narrowing may reuse a context line already removed by exact deduplication, but never invent a source range.
 requested=set(n for a,z in s['requested_ranges'] for n in range(a,z+1))
 assert wanted<=requested,(eid, sorted(wanted-requested))
 selected=allowed&wanted
 if not selected:continue
 b=(ROOT/s['capture_path']).read_bytes();ls=b.splitlines(keepends=True)
 out={**s,'ranges':[metadata(b,ls,a,z) for a,z in spans(selected)],'review_projection':True}
 out['purpose']='B1/B2 missing decisive evidence' if eid.startswith('V') else f"{assignment[path]}: local contract/owner evidence for the exact member"
 chosen[eid]=out

selected_by_path={}
for eid,s in chosen.items():selected_by_path.setdefault(s['source_ref']['path'],[]).append(eid)
assert set(byfile)<=set(selected_by_path),sorted(set(byfile)-set(selected_by_path))
review_members=[]
for x in members:
 y={k:x[k] for k in ['path','historical_record','current_read_state','l1_fact','depth_justification']}
 y['review_domain']=assignment[x['path']]
 y['additional_evidence_ids']=selected_by_path[x['path']]
 y['current_artifact_keys']=['s1.api.surface-disposition']+(['s1.api.sdk-composition'] if x['path'].startswith('packages/sdk-next/') else ['s1.api.schema-contracts'] if x['path'].startswith('packages/schema/') else [])
 review_members.append(y)
for d in domains:
 d['additional_evidence_ids']=sorted(set(e for p in d['member_paths'] for e in selected_by_path[p]))
 d['existing_body_context']=['s1.api.boundaries','s1.api.schema-contracts','s1.api.server-edge','s1.api.surface-disposition']
 if d['id']=='D24':d['existing_body_context']=['s1.api.sdk-composition','s1.api.surface-disposition']
 if d['id'] in ['D03','D04','D07','D16','D17','D19']:d['existing_body_context']+=['s1.api.session-contract','s1.api.stream-contract']

save('semantic-disposition.json',{'schema':'genesis-l1-semantic-disposition/v1','task':'S1-L1-B-v3','source_revision':full['source_revision'],'protocol_revision':full['protocol_revision'],'scope':'orchestra.s1',
 'historical_groups_verbatim':full['historical_groups_verbatim'],'membership_count':190,'review_domain_count':24,'new_read_counts':full['new_read_counts'],
 'domains':domains,'members':review_members,'fixture_generated_documentation_boundary':full['fixture_generated_documentation_boundary'],
 'support_projection_ref':ident(HERE/'support/full-semantic-disposition.json'),
 'support_scope_limit':'Extensive delegate and full projection details remain source-inspection support. Only the bounded domain claims in this review projection are asserted for B3; no independent leaf audit or later-layer conclusion is requested.',
 'mandatory_current_l1_local_source_gaps':[],'review_gap':'Exact-version independent dual judgment remains required. No semantic PASS or whole-layer release.',
 'future_obligations_ref':ident(HERE/'conditional-needs.json')})
save('source-excerpts.json',{'schema':'genesis-excerpt-selection/v1','source_revision':fs['source_revision'],'scope':'orchestra.s1','sources':list(chosen.values()),'prior_evidence_indexes':fs['prior_evidence_indexes'],
 'full_preserved_selection_ref':ident(HERE/'support/full-source-excerpts.json'),'deduplication':fs['deduplication'],
 'projection_scope':'Only B1/B2 and the bounded domain claims in semantic-disposition.json. Extensive delegate observations are not all promoted to batch claims.'})

md=['# B-v3 — domain need disposition for review','',f"Source pin `{full['source_revision']}`; protocol pin `{full['protocol_revision']}`; scope `orchestra.s1`; L1 only.",'',
 'This is the B3 review projection over the exact 190 historical G30/G39/G52/G57 members: 94 Schema, 44 Protocol, 51 Server and SDK tool.ts. The four historical groups and every member record remain verbatim in semantic-disposition.json; new read state is appended separately. Twenty-four domains connect the relevant layers. All 190 captured modules were read in full. This is source evidence awaiting judgment, not a semantic PASS.','',
 'The present mandatory need is purpose, observable contract and local ownership/delegation. The named conditional gaps block broader claims only; they are not a postponed current L1 reading. F02–F08 remain preserved in conditional-needs.json. The other 282 assigned entries retain their historical fixture/generated/test/documentation/support disposition.','',
 'Protocol was read by `/root/producer_b/protocol_triage`, Server by `/root/producer_c`, and Schema/SDK by `/root/producer_b`. The original native requests/responses, literal-read receipts and extensive observations remain in delegates/ and support/. Those additional notes are not all promoted to claims in this packet.','',
 '| Domain | Members | Current L1 source disposition |','| --- | ---: | --- |']
for d in domains:md.append(f"| {d['id']} — {d['title']} | {d['member_count']} | Full literal reads; bounded contract/owner claims supplied; unjudged |")
md+=['','## Domain contracts, exact members and limits','']
for d in domains:
 md += [f"### {d['id']} — {d['title']}",'',d['current_l1_need'],'',d['bounded_claim'],'',
   '**Body relationship:** '+', '.join('`'+k+'`' for k in d['existing_body_context'])+'. These are same-package context links, not accepted build predecessors.','',
   '**Depth:** '+d['why_depth_adequate'],'',
   '**Conditional missing evidence / blocked claim:** '+d['conditional_gap']+' '+d['blocked_dependents'],'',
   '| Exact member | Local L1 purpose | Additional evidence |','| --- | --- | --- |']
 for path in d['member_paths']:
  row=byfile[path];fact=row['l1_fact'].replace('|','\\|').replace('\n',' ')
  md.append(f"| `{path}` | {fact} | {', '.join(selected_by_path[path])} |")
 md+=['']
(HERE/'review-domain-disposition.md').write_text('\n'.join(md))

out=['# B-v3 — compact additional decisive evidence','',f"All source at `{fs['source_revision']}`. Commit/blob/full-source SHA256 and original line/byte/span identities are bound in source-excerpts.json; exact code below is unchanged. L1 only; unjudged.",'',
 'Scope: B1/B2 and the 24 bounded domains in review-domain-disposition.md. C01–C47/S01–S38 are referenced, not reprinted. Extensive native selections remain in delegates/ and support/full-review-supplement.md. The separate complete-branch-context.md contains just the two complete B2 branches, with exactly three reused closing/release lines from C34.','',
 '## Artifact → decisive evidence','',
 '| Artifact | Evidence |','| --- | --- |',
 '| s1.api.server-edge | V01 + existing C29; D10/D11/D22 ownership boundaries |',
 '| s1.api.session-contract | V02–V04 + existing C21/S16; complete source comparison, no A synthesis |',
 '| s1.api.stream-contract | V05 (production allocation/capacity), V06 + C34 (finally) |',
 '| s1.api.client-projection | V06 + C34 (binary return and finally) |',
 '| s1.api.schema-contracts | Q001–Q094 through the domain/member map |',
 '| s1.api.sdk-composition | Q095 complete Core tool facade |',
 '| s1.api.surface-disposition | Domain/member map of all Q/P/G57 selections |',
 '| s1.api.boundaries; s1.api.codegen | Bodies unchanged; original C/S evidence retained |','']
for s in sorted(chosen.values(),key=lambda x:(not x['id'].startswith('V'),x['id'])):
 rf=s['source_ref'];p=rf['path'];ls=(ROOT/s['capture_path']).read_bytes().splitlines(keepends=True)
 out += [f"## {s['id']} — {p}",'',f"Git blob `{rf['git_blob_sha']}`; source SHA256 `{rf['sha256']}`; {rf['byte_length']} bytes at the common source pin.",'']
 for rg in s['ranges']:
  raw=b''.join(ls[rg['start_line']-1:rg['end_line']])
  # Preserve every excerpt byte, including final blank lines. The joining newline
  # restores exactly the one final LF removed here before the closing fence.
  assert raw.endswith(b'\n'), (s['id'], rg)
  out += [f"Lines {rg['start_line']}–{rg['end_line']}; {rg['byte_length']} exact bytes; span SHA256 `{rg['sha256']}`.",'','```ts',raw.decode().removesuffix('\n'),'```','']
(HERE/'review-supplement.md').write_text('\n'.join(out))
save('review-projection-receipt.json',{'schema':'genesis-l1-review-projection/v1','member_count':190,'review_domain_count':24,'review_members_exact':True,
 'extensive_support_preserved':[ident(HERE/'support'/('full-'+rel)) for rel in ['semantic-disposition.json','source-excerpts.json','review-supplement.md']],
 'compact_claims_ref':ident(HERE/'review-domain-disposition.md'),'compact_evidence_ref':ident(HERE/'review-supplement.md'),
 'exact_line_ranges':sum(len(s['ranges']) for s in chosen.values()),'exact_lines':sum(r['end_line']-r['start_line']+1 for s in chosen.values() for r in s['ranges']),
 'purpose':'Economic projection of already preserved exact readings onto original B1/B2/B3 requirements. Omitted support details are not asserted by the compact batch; source originals and historical records are unchanged.',
 'semantic_acceptance':'unjudged'})
print(json.dumps({'domains':24,'members':190,'compact_evidence_bytes':(HERE/'review-supplement.md').stat().st_size,'disposition_md_bytes':(HERE/'review-domain-disposition.md').stat().st_size,'selected_source_records':len(chosen),'lines':sum(r['end_line']-r['start_line']+1 for s in chosen.values() for r in s['ranges'])},indent=2))
