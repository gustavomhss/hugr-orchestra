import { expect, test } from "bun:test"
import type { ResearchProcess } from "../../src/research-toolkit/process"
import { ReviewCargoAuditReport } from "../../src/review-toolkit/cargo-audit-report"

const RULE = "cargo-audit/advisory"
const PACK = "cargo-audit"
const PATH = "vendor/Cargo.lock"
const SOURCE = "registry+https://github.com/rust-lang/crates.io-index"
const SUM = "ab".repeat(32)
const COMMIT = "c".repeat(40)
const ID = "RUSTSEC-2024-0001"
const NOTICE = "RUSTSEC-2024-0002"

type Pkg = { readonly name: string; readonly version: string; readonly source?: string }
type Range = { readonly line: number; readonly endLine: number }

const keyOf = (pkg: Pkg) => `${pkg.name}:${pkg.version}:${pkg.source ?? SOURCE}`

function canonical(packages: readonly Pkg[], lead = "") {
  let text = `${lead}# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n`
  const ranges: Record<string, Range> = {}
  for (const pkg of packages) {
    text += "\n"
    const line = text.split("\n").length
    const source = pkg.source ?? SOURCE
    text += `[[package]]\nname = "${pkg.name}"\nversion = "${pkg.version}"\nsource = "${source}"\nchecksum = "${SUM}"\n`
    ranges[keyOf({ ...pkg, source })] = { line, endLine: text.split("\n").length - 1 }
  }
  return { text, ranges }
}

const alpha = { name: "alpha", version: "1.0.0" } as const
const beta = { name: "beta", version: "2.0.0" } as const
const twinOld = { name: "twin", version: "1.0.0" } as const
const twinNew = { name: "twin", version: "2.0.0" } as const
const base = canonical([alpha, beta])
const shifted = canonical([alpha, beta], "# shifted\n")
const twins = canonical([twinOld, twinNew])

function crate(pkg: Pkg) {
  return { name: pkg.name, version: pkg.version, source: pkg.source ?? SOURCE, checksum: SUM, dependencies: [] }
}

function advisory(id: string, name: string, title = "demo title", informational: string | null = null) {
  return {
    id, package: name, title, description: "demo", date: "2024-01-15", aliases: [], related: [],
    collection: "crates", categories: [], keywords: [], cvss: null, informational, references: [],
    source: SOURCE, url: null, withdrawn: null, license: "CC0-1.0",
  }
}

function vulnerability(pkg: Pkg, id = ID, title = "demo title") {
  return {
    advisory: advisory(id, pkg.name, title),
    versions: { patched: [">=9.9.9"], unaffected: [] },
    affected: null,
    package: crate(pkg),
  }
}

function warning(kind: string, pkg: Pkg, id: string | null) {
  return {
    kind,
    package: crate(pkg),
    advisory: id === null ? null : advisory(id, pkg.name, `${kind} title`, kind === "yanked" ? null : kind),
    affected: null,
    versions: null,
  }
}

function report(patch: {
  list?: readonly unknown[]
  found?: boolean
  count?: number
  warnings?: Record<string, readonly unknown[]>
  ignore?: readonly string[]
  severity?: string | null
  arch?: readonly string[]
  os?: readonly string[]
  info?: readonly string[]
  drop?: "database" | "lockfile" | "settings" | "vulnerabilities" | "warnings"
} = {}) {
  const list = patch.list ?? []
  const body: Record<string, unknown> = {
    database: { "advisory-count": 2, "last-commit": COMMIT, "last-updated": "2024-06-01T00:00:00Z" },
    lockfile: { "dependency-count": 2 },
    settings: {
      target_arch: patch.arch ?? [],
      target_os: patch.os ?? [],
      severity: patch.severity === undefined ? null : patch.severity,
      ignore: patch.ignore ?? [],
      informational_warnings: patch.info ?? ["unmaintained", "unsound", "notice"],
    },
    vulnerabilities: { found: patch.found ?? list.length > 0, count: patch.count ?? list.length, list },
    warnings: patch.warnings ?? {},
  }
  if (patch.drop) delete body[patch.drop]
  return JSON.stringify(body)
}

const clean = report()
const vuln = report({ list: [vulnerability(alpha)] })
const fp = (id: string, pkg: Pkg) => `${id}:${pkg.name}:${pkg.version}:${pkg.source ?? SOURCE}`

function ok(text: string, lock = base.text) {
  const parsed = ReviewCargoAuditReport.parse(text, PATH, lock)
  if (parsed.status !== "ok") throw new Error(`${parsed.status}:${parsed.reason}`)
  return parsed
}

function refused(text: string, lock: string, reason: string) {
  expect(ReviewCargoAuditReport.parse(text, PATH, lock)).toEqual({ status: "acquisition-error", reason })
}

function ran(patch: Partial<ResearchProcess.Outcome>): ResearchProcess.Outcome {
  return {
    exitCode: 0, durationMs: 1, timedOut: false, overflow: false, memoryExceeded: false,
    stdout: { data: Buffer.alloc(0), bytes: 0, truncated: false },
    stderr: { data: Buffer.alloc(0), bytes: 0, truncated: false },
    ...patch,
  }
}

test("clean report is zero findings and not a pass-by-omission", () => {
  const parsed = ok(clean)
  expect(parsed.results).toEqual([])
  expect(parsed.excluded).toEqual([])
  expect(parsed.status).toBe("ok")
})

test("one vulnerability binds the actual package block and a shift-stable fingerprint", () => {
  const parsed = ok(vuln)
  const moved = ok(vuln, shifted.text)
  expect(ok(vuln, base.text.replace("version = 3", "version = 4")).results).toEqual(parsed.results)
  expect(parsed.results).toHaveLength(1)
  expect(parsed.excluded).toEqual([])
  const row = parsed.results[0]
  expect(row).toMatchObject({
    pack: PACK, rule: RULE, path: PATH, ...base.ranges[keyOf(alpha)],
    toolFingerprint: fp(ID, alpha), nativeSeverity: "error", suppressions: [],
  })
  expect(row.message).toContain(ID)
  expect(row.message).toContain("demo title")
  expect(row.rule).toBe(RULE)
  expect(moved.results[0].toolFingerprint).toBe(row.toolFingerprint)
  expect(moved.results[0].line).toBe(shifted.ranges[keyOf(alpha)].line)
  expect(moved.results[0].endLine).toBe(shifted.ranges[keyOf(alpha)].endLine)
  expect(moved.results[0].line).not.toBe(row.line)
})

test("informational advisories are warning candidates and a second version is an exact identity", () => {
  for (const kind of ["unmaintained", "unsound", "notice"] as const) {
    const parsed = ok(report({
      warnings: { [kind]: [warning(kind, beta, NOTICE)] },

    }))
    expect(parsed.results).toHaveLength(1)
    expect(parsed.results[0]).toMatchObject({
      pack: PACK, rule: RULE, path: PATH, ...base.ranges[keyOf(beta)],
      toolFingerprint: fp(NOTICE, beta), nativeSeverity: "warning", suppressions: [],
    })
    expect(parsed.results[0].message).toContain(NOTICE)
    expect(parsed.results.every((item) => item.nativeSeverity !== "error")).toBe(true)
  }
  const selected = ok(report({ list: [vulnerability(twinNew, ID)] }), twins.text)
  expect(selected.results).toHaveLength(1)
  expect(selected.results[0]).toMatchObject({ ...twins.ranges[keyOf(twinNew)], toolFingerprint: fp(ID, twinNew) })
  expect(selected.results[0].line).not.toBe(twins.ranges[keyOf(twinOld)].line)
})

test("filtered, incoherent, unknown, and unmapped reports are acquisition errors", () => {
  const duplicate = `${base.text}\n[[package]]\nname = "alpha"\nversion = "1.0.0"\nsource = "${SOURCE}"\nchecksum = "${SUM}"\n`
  const inline = `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\npackage = [{ name = "alpha", version = "1.0.0", source = "${SOURCE}" }]\n`
  const cases: ReadonlyArray<readonly [string, string, string]> = [
    ["{", base.text, "malformed-json"],
    [clean, "", "lockfile-layout-unsupported"],
    [clean, base.text.replace("version = 3", "version = 5"), "lockfile-layout-unsupported"],
    [clean, inline, "lockfile-layout-unsupported"],
    [clean, duplicate, "lockfile-package-ambiguous"],
    [vuln, duplicate, "lockfile-package-ambiguous"],
    [report({ list: [vulnerability({ name: "gamma", version: "1.0.0" })] }), base.text, "lockfile-package-missing"],
    [report({ ignore: ["RUSTSEC-2020-0001"] }), base.text, "ignore-filter"],
    [report({ severity: "high" }), base.text, "severity-filter"],
    [report({ arch: ["x86_64"] }), base.text, "target-filter"],
    [report({ os: ["linux"] }), base.text, "target-filter"],
    [report({ warnings: { yanked: [] } }), base.text, "warning-yanked"],
    [report({ warnings: { yanked: [warning("yanked", alpha, null)] } }), base.text, "warning-yanked"],
    [report({ warnings: { other: [] } }), base.text, "warning-unknown"],
    [report({ warnings: { unmaintained: [warning("unmaintained", alpha, null)] } }), base.text, "advisory-missing"],
    [report({ list: [vulnerability(alpha, "CVE-2017-1000168")] }), base.text, "advisory-id-invalid"],
    [report({ list: [vulnerability(alpha, "RUSTSEC-0000-0000")] }), base.text, "advisory-id-invalid"],
    [report({ list: [vulnerability(alpha, "RUSTSEC-2018-1")] }), base.text, "advisory-id-invalid"],
    [report({ list: [vulnerability(alpha, ID, "")] }), base.text, "title-invalid"],
    [report({ list: [{ ...vulnerability(alpha), package: { ...crate(alpha), name: "" } }] }), base.text, "package-invalid"],
    [report({ list: [{ ...vulnerability(alpha), advisory: { ...vulnerability(alpha).advisory, package: "other" } }] }), base.text, "package-invalid"],
    [report({ found: false, count: 1, list: [vulnerability(alpha)] }), base.text, "count-mismatch"],
    [report({ found: true, count: 0, list: [] }), base.text, "count-mismatch"],
    [report({ found: true, count: 1, list: [] }), base.text, "count-mismatch"],
    [report({ found: false, count: 0, list: [vulnerability(alpha)] }), base.text, "count-mismatch"],
    [report({ drop: "vulnerabilities" }), base.text, "report-invalid"],
    [report({ drop: "warnings" }), base.text, "report-invalid"],
    [report({ drop: "settings" }), base.text, "report-invalid"],
  ]
  for (const [text, lock, reason] of cases) refused(text, lock, reason)
})

test("settle maps timeout and memory to not-run and every other break to acquisition-error", () => {
  expect(ReviewCargoAuditReport.settle(ran({}), clean, PATH, base.text)).toEqual({ status: "ok", results: [], excluded: [] })
  expect(ReviewCargoAuditReport.settle(ran({}), report({ warnings: { notice: [warning("notice", beta, NOTICE)] }, info: ["unmaintained", "unsound", "notice"] }), PATH, base.text).status).toBe("ok")
  expect(ReviewCargoAuditReport.settle(ran({ exitCode: 1 }), vuln, PATH, base.text).status).toBe("ok")
  expect(ReviewCargoAuditReport.settle(ran({ timedOut: true, exitCode: null }), vuln, PATH, base.text)).toEqual({ status: "not-run", reason: "timeout" })
  expect(ReviewCargoAuditReport.settle(ran({ memoryExceeded: true, exitCode: null }), vuln, PATH, base.text)).toEqual({ status: "not-run", reason: "memory cap" })
  const errors: ReadonlyArray<readonly [ResearchProcess.Outcome, string, string]> = [
    [ran({ overflow: true }), clean, "output cap"],
    [ran({ failure: "spawn-failed", exitCode: null }), clean, "spawn-failed"],
    [ran({ exitCode: null }), clean, "signal"],
    [ran({ exitCode: 2 }), clean, "exit 2"],
    [ran({ exitCode: 2 }), vuln, "exit 2"],
    [ran({ exitCode: 0 }), vuln, "exit 0"],
    [ran({ exitCode: 1 }), clean, "exit 1"],
    [ran({ exitCode: 1 }), report({ warnings: { notice: [warning("notice", beta, NOTICE)] }, info: ["unmaintained", "unsound", "notice"] }), "exit 1"],
    [ran({}), "{", "malformed-json"],
  ]
  for (const [outcome, text, reason] of errors) {
    expect(ReviewCargoAuditReport.settle(outcome, text, PATH, base.text)).toEqual({ status: "acquisition-error", reason })
  }
})


test("informational warning settings cannot suppress any native category", () => {
  const fixture = canonical([{ name: "alpha", version: "1.0.0" }])
  for (const info of [[], ["notice"], ["unmaintained", "unsound", "notice", "other"], ["unmaintained", "unsound", "notice", "notice"]]) {
    expect(ReviewCargoAuditReport.parse(report({ info }), PATH, fixture.text)).toEqual({ status: "acquisition-error", reason: "informational-filter" })
  }
})
