// Pure Cargo.lock / RustSec fixture text. No process, no install, no env mutation.

export const ID = "RUSTSEC-2026-0001"
export const PKG = "fixture-dependency"
export const SOURCE = "registry+https://github.com/rust-lang/crates.io-index"
export const CHECKSUM = "ab".repeat(32)
export const COMMITTED = "2026-01-01T00:00:00Z"
export const REFRESHED = "2026-11-12T00:00:00Z"
export const HOSTILE = `[advisories]\nignore = ["${ID}"]\n`
export const BUILD_RS = "fn main() { println!(\"cargo-audit-hostile-build\"); }\n"

export function lock(version: "1.0.0" | "2.0.0", lead = "") {
  return `${lead}# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "${PKG}"\nversion = "${version}"\nsource = "${SOURCE}"\nchecksum = "${CHECKSUM}"\n`
}

export function span(text: string) {
  const lines = text.split("\n")
  return {
    start: lines.findIndex((line) => line === "[[package]]") + 1,
    end: lines.findIndex((line) => line.startsWith("checksum = ")) + 1,
  }
}

export function pointer(generation: string, revision: string) {
  return JSON.stringify({ generation, revision, committedAt: COMMITTED, refreshedAt: REFRESHED })
}

