export * as ReviewCargoAuditLock from "./cargo-audit-lock"

const HEADER = ["# This file is automatically @generated by Cargo.", "# It is not intended for manual editing."] as const

export type Block = { readonly name: string; readonly version: string; readonly source?: string; readonly line: number; readonly endLine: number }
type Refused = { readonly status: "acquisition-error"; readonly reason: string }

export function parse(lockText: string): { status: "ok"; blocks: readonly Block[] } | Refused {
  let parsed: unknown
  try {
    parsed = Bun.TOML.parse(lockText)
  } catch {
    return fail("lockfile-layout-unsupported")
  }
  if (!record(parsed) || (parsed.version !== 3 && parsed.version !== 4)) return fail("lockfile-layout-unsupported")
  const semantic = semanticPackages(parsed.package)
  const lexical = lexicalPackages(lockText)
  if (!semantic || !lexical || semantic.length !== lexical.length) return fail("lockfile-layout-unsupported")
  const agreed = semantic.every((pkg, index) => pkg.name === lexical[index]?.name && pkg.version === lexical[index]?.version && pkg.source === lexical[index]?.source)
  if (!agreed) return fail("lockfile-layout-unsupported")
  const seen = new Set<string>()
  for (const pkg of lexical) {
    const key = `${pkg.name}\0${pkg.version}\0${pkg.source ?? ""}`
    if (seen.has(key)) return fail("lockfile-package-ambiguous")
    seen.add(key)
  }
  return { status: "ok", blocks: lexical }
}

function semanticPackages(value: unknown): Array<{ name: string; version: string; source?: string }> | undefined {
  if (value === undefined) return []
  if (!Array.isArray(value)) return undefined
  const packages: Array<{ name: string; version: string; source?: string }> = []
  for (const item of value) {
    if (!record(item) || typeof item.name !== "string" || typeof item.version !== "string") return undefined
    if (item.source !== undefined && item.source !== null && typeof item.source !== "string") return undefined
    packages.push({ name: item.name, version: item.version, source: typeof item.source === "string" ? item.source : undefined })
  }
  return packages
}

function lexicalPackages(text: string): Block[] | undefined {
  const lines = text.split("\n")
  const blocks: Block[] = []
  let header = 0
  let sawVersion = false
  let index = 0
  while (index < lines.length) {
    const line = lines[index]?.replace(/\r$/, "") ?? ""
    if (line === "") {
      index += 1
      continue
    }
    if (line.startsWith("#")) {
      if (header < HEADER.length && line === HEADER[header]) header += 1
      index += 1
      continue
    }
    if (line === "version = 3" || line === "version = 4") {
      if (header !== HEADER.length || sawVersion) return undefined
      sawVersion = true
      index += 1
      continue
    }
    if (line !== "[[package]]" || !sawVersion) return undefined
    const block = readBlock(lines, index)
    if (!block) return undefined
    blocks.push(block.block)
    index = block.next
  }
  if (!sawVersion) return undefined
  return blocks
}

function readBlock(lines: readonly string[], start: number): { block: Block; next: number } | undefined {
  let name: string | undefined
  let version: string | undefined
  let source: string | undefined
  let end = start
  let index = start + 1
  let dependencies = false
  while (index < lines.length) {
    const line = lines[index]?.replace(/\r$/, "") ?? ""
    const trimmed = line.trim()
    if (trimmed === "[[package]]") break
    if (trimmed === "") {
      index += 1
      continue
    }
    if (dependencies) {
      if (trimmed !== "]" && !/^".*",?$/.test(trimmed)) return undefined
      dependencies = trimmed !== "]"
      end = index
      index += 1
      continue
    }
    if (trimmed.startsWith("#")) {
      index += 1
      continue
    }
    const assigned = trimmed.match(/^(name|version|source|checksum) = "(.*)"$/)
    if (assigned) {
      if (assigned[2]?.includes("\\")) return undefined
      if (assigned[1] === "name") {
        if (name !== undefined) return undefined
        name = assigned[2]
      }
      if (assigned[1] === "version") {
        if (version !== undefined) return undefined
        version = assigned[2]
      }
      if (assigned[1] === "source") {
        if (source !== undefined) return undefined
        source = assigned[2]
      }
      end = index
      index += 1
      continue
    }
    if (trimmed === "dependencies = []") {
      end = index
      index += 1
      continue
    }
    if (trimmed === "dependencies = [") {
      dependencies = true
      end = index
      index += 1
      continue
    }
    return undefined
  }
  if (dependencies || name === undefined || version === undefined) return undefined
  return { block: { name, version, source, line: start + 1, endLine: end + 1 }, next: index }
}

function record(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value)
}

function fail(reason: string): Refused {
  return { status: "acquisition-error", reason }
}
