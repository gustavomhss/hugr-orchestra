import { expect, test } from "bun:test"
import { Elf } from "../src/elf"

test("pure ELF byte admission respects view offsets and retains named libc/mapping failures", () => {
  const storage = new Uint8Array(544)
  const bytes = storage.subarray(16, 528)
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  bytes.set([127, 69, 76, 70, 2, 1, 1])
  view.setUint16(16, 3, true)
  view.setUint16(18, 62, true)
  view.setUint32(20, 1, true)
  view.setBigUint64(32, 64n, true)
  view.setUint16(54, 56, true)
  view.setUint16(56, 2, true)
  view.setUint32(64, 1, true)
  view.setBigUint64(80, 0x1000n, true)
  view.setBigUint64(96, 512n, true)
  view.setBigUint64(104, 512n, true)
  view.setUint32(120, 2, true)
  view.setBigUint64(128, 176n, true)
  view.setBigUint64(136, 0x10b0n, true)
  view.setBigUint64(152, 64n, true)
  view.setBigUint64(160, 64n, true)
  const name = new TextEncoder().encode("libc.so.6\0")
  bytes.set(name, 352)
  ;[[5n, 0x1160n], [10n, BigInt(name.length)], [1n, 0n], [0n, 0n]].forEach(([tag, value], i) => {
    view.setBigInt64(176 + i * 16, tag, true)
    view.setBigUint64(184 + i * 16, value, true)
  })
  expect(Elf.requireLibc(bytes, "glibc", "view")).toEqual({ machine: 62, interpreter: undefined, needed: ["libc.so.6"] })
  expect(() => Elf.requireLibc(bytes, "musl", "view")).toThrow("ELF_LIBC_MISMATCH: view")
  expect(() => Elf.inspect(bytes.subarray(0, 63), "view")).toThrow("ELF_TRUNCATED: view")
  view.setBigUint64(128, 256n, true)
  expect(() => Elf.inspect(bytes, "view")).toThrow("ELF_DYNAMIC_OFFSET_MISMATCH: view")
  view.setBigUint64(128, 176n, true)
  expect(Elf.inspect(bytes, "view").needed).toEqual(["libc.so.6"])
})
