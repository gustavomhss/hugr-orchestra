test("preflight actual captures arm/check/disarm; failed rearm revokes earlier green", async () => {
  const f = await fixture()
  const head = await f.init()
  expect(await operation({ operation: "preflight-arm", wave: "wave", checks: capture(check("smoke", "pass", head)), requiredChecks: ["smoke"] }, f.context)).toMatchObject({ armed: true })
  expect(await operation({ operation: "preflight-check", wave: "wave" }, f.context)).toMatchObject({ status: "PASS" })
  expect(await operation({ operation: "preflight-disarm", wave: "wave" }, f.context)).toMatchObject({ armed: false })
  expect(await operation({ operation: "preflight-check", wave: "wave" }, f.context)).toMatchObject({ status: "FAIL", failures: ["PREFLIGHT_NOT_ARMED"] })
  const failed = await operation<{ armed: boolean; failures: string[] }>({ operation: "preflight-arm", wave: "wave", checks: capture(check("smoke", "skip", head)), requiredChecks: ["smoke"] }, f.context)
  expect(failed.armed).toBe(false)
  expect(failed.failures).toContain("PREFLIGHT_CHECK_SKIP: smoke")
  expect(await operation({ operation: "preflight-check", wave: "wave" }, f.context)).toMatchObject({ status: "FAIL", failures: ["PREFLIGHT_NOT_ARMED", "PREFLIGHT_CHECK_SKIP: smoke"] })
})
test("commitlint reads actual Git commit messages and detects invalid subjects", async () => {
  const f = await fixture()
  await f.init()
  await f.runGit("checkout", "-b", "work")
  await Bun.write(join(f.root, "owned.ts"), "export const value = 2\n")
  await f.runGit("add", "owned.ts")
  await f.runGit("commit", "-m", "fix: preserved contract")
  expect(await operation({ operation: "commitlint" }, f.context)).toMatchObject({ status: "PASS" })
  await Bun.write(join(f.root, "owned.ts"), "export const value = 3\n")
  await f.runGit("add", "owned.ts")
  await f.runGit("commit", "-m", "bad subject")
  expect(await operation({ operation: "commitlint" }, f.context)).toMatchObject({ status: "FAIL" })
})
