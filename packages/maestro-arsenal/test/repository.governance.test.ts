test("changelog gate checks actual parsed package/version/body; proposals remain uncurated", async () => {
  const f = await fixture()
  await f.init()
  expect(await operation({ operation: "changelog-check", packagePath: "package.json", changelogPath: "CHANGELOG.md" }, f.context)).toMatchObject({ status: "PASS" })
  const proposal = await operation<{ entry: string; written: boolean }>({ operation: "changelog-propose", version: "1.0.0", title: "Release", date: "2026-09-30" }, f.context)
  expect(proposal.written).toBe(false)
  await Bun.write(join(f.root, "CHANGELOG.md"), proposal.entry)
  expect((await changelog(f.context, f.root, "package.json", "CHANGELOG.md")).failures).toContain("CHANGELOG_UNCURATED")
  await Bun.write(join(f.root, "CHANGELOG.md"), "# no release section\n")
  await expect(changelog(f.context, f.root, "package.json", "CHANGELOG.md")).rejects.toThrow("CHANGELOG_SECTION_MISSING")
  await Bun.write(join(f.root, "package.json"), JSON.stringify({ version: null }))
  await expect(changelog(f.context, f.root, "package.json", "CHANGELOG.md")).rejects.toThrow("PACKAGE_VERSION_MISSING_OR_INVALID")
})
test("release validates actual HEAD/checks/changelog/dev/tag; never creates tag or publishes", async () => {
  const f = await fixture()
  const head = await f.init()
  const input = { packagePath: "package.json", changelogPath: "CHANGELOG.md", checks: capture(check("FULL", "pass", head)), requiredChecks: ["FULL"] }
  expect(await operation({ operation: "release-propose", ...input }, f.context)).toMatchObject({ status: "LOCAL_READY", branch: "dev", executed: false })
  expect(await f.runGit("tag", "--list")).toBe("")
  expect((await releaseProposal(f.context, f.root, { ...input, checks: capture(check("FULL", "skip", head)) })).failures).toContain("RELEASE_CHECK_SKIP: FULL")
  expect((await releaseProposal(f.context, f.root, { ...input, checks: capture(check("OTHER", "pass", head)) })).failures).toContain("RELEASE_CHECK_MISSING: FULL")
  await Bun.write(join(f.root, "owned.ts"), "changed\n")
  expect((await releaseProposal(f.context, f.root, input)).failures).toContain("RELEASE_DIRTY_TREE")
})
