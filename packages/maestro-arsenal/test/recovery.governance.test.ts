import { expect, test } from "bun:test"
import { join } from "node:path"
import { unlink, symlink } from "node:fs/promises"
import { recoveryBegin, recoveryPrepare, recoveryRestore } from "../src/governance/recovery.ts"
import { fixture, operation, check, capture } from "./fixtures.governance.ts"
import { rethrow } from "./rejection.ts"
test("selective recovery restores committed owned file; preserves user dirt, untracked, HEAD/index", async () => {
  const f = await fixture()
  const baseline = await f.init()
  expect(await operation({ operation: "recovery-begin", wave: "wave", ownedPaths: ["owned.ts"] }, f.context)).toMatchObject({ baseline, globalAtomicTransaction: false })
  await Bun.write(join(f.root, "owned.ts"), "export const value = 9\n")
  await Bun.write(join(f.root, "other.ts"), "user dirt\n")
  await Bun.write(join(f.root, "user.txt"), "untracked user content\n")
  const index = await f.runGit("write-tree")
  const plan = await operation<{ token: string }>({ operation: "recovery-prepare", wave: "wave" }, f.context)
  expect(await operation({ operation: "recovery-restore", token: plan.token }, f.context)).toMatchObject({ status: "RESTORED_OWNED_FILES", restored: ["owned.ts"], globalAtomicTransaction: false, externalEffectsReversed: false })
  expect(await Bun.file(join(f.root, "owned.ts")).text()).toBe("export const value = 1\n")
  expect(await Bun.file(join(f.root, "other.ts")).text()).toBe("user dirt\n")
  expect(await Bun.file(join(f.root, "user.txt")).text()).toBe("untracked user content\n")
  expect(await f.runGit("rev-parse", "HEAD")).toBe(baseline)
  expect(await f.runGit("write-tree")).toBe(index)
  expect(await operation({ operation: "recovery-status", wave: "wave" }, f.context)).toMatchObject({ baseline })
})
test("recovery refuses concurrent dirt changes after prepare", async () => {
  const f = await fixture()
  await f.init()
  await recoveryBegin(f.context, f.root, "wave", ["owned.ts"])
  await Bun.write(join(f.root, "owned.ts"), "wave dirt\n")
  const plan = await recoveryPrepare(f.context, f.root, "wave")
  await Bun.write(join(f.root, "other.ts"), "concurrent user edit\n")
  expect(await rethrow(recoveryRestore(f.context, f.root, plan.token))).toThrow("RECOVERY_CONCURRENT_HEAD_OR_DIRT_CHANGED")
  expect(await Bun.file(join(f.root, "owned.ts")).text()).toBe("wave dirt\n")
})
