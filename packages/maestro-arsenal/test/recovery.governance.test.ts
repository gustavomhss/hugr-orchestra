test("recovery re-creates deleted committed owned file and rejects symlink substitution", async () => {
  const f = await fixture()
  await f.init()
  await recoveryBegin(f.context, f.root, "wave", ["owned.ts"])
  await unlink(join(f.root, "owned.ts"))
  const plan = await recoveryPrepare(f.context, f.root, "wave")
  await recoveryRestore(f.context, f.root, plan.token)
  expect(await Bun.file(join(f.root, "owned.ts")).text()).toBe("export const value = 1\n")
  await unlink(join(f.root, "owned.ts"))
  await Bun.write(join(f.state, "outside.ts"), "outside user file\n")
  await symlink(join(f.state, "outside.ts"), join(f.root, "owned.ts"))
  expect(await rethrow(recoveryPrepare(f.context, f.root, "wave"))).toThrow("PATH_SYMLINK_DENIED")
  expect(await Bun.file(join(f.state, "outside.ts")).text()).toBe("outside user file\n")
})
test("recovery restores binary blobs byte-for-byte without text decoding", async () => {
  const f = await fixture()
  await f.init()
  const bytes = Buffer.from([0, 255, 254, 128, 13, 10, 42])
  await Bun.write(join(f.root, "owned.bin"), bytes)
  await f.runGit("add", "owned.bin")
  await f.runGit("commit", "-m", "test: binary baseline")
  await recoveryBegin(f.context, f.root, "wave", ["owned.bin"])
  await Bun.write(join(f.root, "owned.bin"), Buffer.from([0, 1]))
  const plan = await recoveryPrepare(f.context, f.root, "wave")
  await recoveryRestore(f.context, f.root, plan.token)
  expect(Buffer.from(await Bun.file(join(f.root, "owned.bin")).arrayBuffer())).toEqual(bytes)
})
test("recovery ownership refuses git metadata under either separator and its NTFS aliases before any read", async () => {
  const f = await fixture()
  await f.init()
  // Pure string refusal, so it holds on every OS; on Windows these spellings open the real .git directory.
  await Promise.all([".git\\config", "sub\\.git\\HEAD", ".GIT/config", "git~1\\config", ".git.\\config", "C:.git\\config", "\\\\server\\share\\owned.ts"].map(async (path) =>
    expect(await rethrow(recoveryBegin(f.context, f.root, "wave", [path]))).toThrow("RECOVERY_GIT_METADATA_DENIED")))
  expect(f.permissions.some((request) => request.effect === "read")).toBe(false)
})
test("recovery restores an owned file in a subdirectory", async () => {
  const f = await fixture()
  await f.init()
  await Bun.write(join(f.root, "src", "nested.ts"), "export const nested = 1\n")
  await f.runGit("add", "src/nested.ts")
  await f.runGit("commit", "-m", "test: nested baseline")
  await recoveryBegin(f.context, f.root, "wave", ["src/nested.ts"])
  await Bun.write(join(f.root, "src", "nested.ts"), "wave dirt\n")
  const plan = await recoveryPrepare(f.context, f.root, "wave")
  // Git lists the temporary restore file with "/"; only Windows spells it differently natively.
  expect(await recoveryRestore(f.context, f.root, plan.token)).toMatchObject({ restored: ["src/nested.ts"] })
  expect(await Bun.file(join(f.root, "src", "nested.ts")).text()).toBe("export const nested = 1\n")
})
